/** Where file bytes live. Local disk in development and tests; an S3-compatible bucket (Railway) in production. */
export interface StorageDriver {
  readonly name: 'local' | 's3';
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  /**
   * A URL the browser can download from directly for `expiresIn` seconds, or null when the
   * driver can't serve directly (local disk): then the API serves the file through a signed link.
   */
  presignedGetUrl(
    key: string,
    opts: { expiresIn: number; filename: string; contentType: string },
  ): Promise<string | null>;
}

export const STORAGE_DRIVER = Symbol('STORAGE_DRIVER');

/** Keys are generated by the app; this guards the local driver against path tricks anyway. */
export function assertSafeKey(key: string): void {
  if (!/^[a-z0-9-]+(\/[a-zA-Z0-9._-]+)+$/.test(key) || key.includes('..')) {
    throw new Error(`Unsafe storage key: ${key}`);
  }
}
