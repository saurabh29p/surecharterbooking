import type {
  AircraftCategory,
  CancellationSchedule,
  LeadSource,
  LegStatus,
  WeddingStatus,
} from '@shubhjets/shared';
import {
  Column,
  CreateDateColumn,
  Entity,
  PrimaryColumn,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Audited } from '../audit/audited.js';
import { paise } from '../db/transformers.js';

@Audited('wedding', { ignore: ['createdBy', 'number', 'code'] })
@Entity('wedding')
export class Wedding {
  @PrimaryGeneratedColumn('uuid') id!: string;
  /** From a database sequence starting at 101; read-only here. */
  @Column({ type: 'integer', insert: false, update: false }) number!: number;
  /** "W-101", generated by the database from the number. */
  @Column({ type: 'text', insert: false, update: false }) code!: string;
  @Column('uuid', { name: 'business_profile_id', nullable: true }) businessProfileId!:
    string | null;
  @Column('uuid', { name: 'partner_id', nullable: true }) partnerId!: string | null;
  @Column('uuid', { name: 'client_id', nullable: true }) clientId!: string | null;
  @Column('text', { name: 'venue_city', nullable: true }) venueCity!: string | null;
  @Column('date', { name: 'starts_on', nullable: true }) startsOn!: string | null;
  @Column('date', { name: 'ends_on', nullable: true }) endsOn!: string | null;
  @Column('text', { name: 'lead_source' }) leadSource!: LeadSource;
  @Column('text', { name: 'utm_source', nullable: true }) utmSource!: string | null;
  @Column('text', { name: 'utm_medium', nullable: true }) utmMedium!: string | null;
  @Column('text', { name: 'utm_campaign', nullable: true }) utmCampaign!: string | null;
  @Column('text', { name: 'utm_term', nullable: true }) utmTerm!: string | null;
  @Column('text', { name: 'utm_content', nullable: true }) utmContent!: string | null;
  @Column('text', { name: 'landing_page', nullable: true }) landingPage!: string | null;
  @Column('text') status!: WeddingStatus;
  @Column('text', { name: 'lost_reason', nullable: true }) lostReason!: string | null;
  @Column('integer', { name: 'required_payment_bps' }) requiredPaymentBps!: number;
  @Column('integer', { name: 'payment_plan_bps', array: true }) paymentPlanBps!: number[];
  @Column('char', { name: 'place_of_supply_state', length: 2, nullable: true })
  placeOfSupplyState!: string | null;
  @Column('text', { nullable: true }) notes!: string | null;
  @Column('timestamptz', { name: 'deleted_at', nullable: true }) deletedAt!: Date | null;
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt!: Date;
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' }) updatedAt!: Date;
  @Column('uuid', { name: 'created_by', nullable: true }) createdBy!: string | null;
}

const hhmm = { to: (v: string | null) => v, from: (v: string | null) => (v ? v.slice(0, 5) : v) };

@Audited('leg')
@Entity('leg')
export class Leg {
  @PrimaryGeneratedColumn('uuid') id!: string;
  @Column('uuid', { name: 'wedding_id' }) weddingId!: string;
  @Column('integer') seq!: number;
  @Column('char', { name: 'from_iata', length: 3 }) fromIata!: string;
  @Column('char', { name: 'to_iata', length: 3 }) toIata!: string;
  @Column('date', { name: 'flight_date' }) flightDate!: string;
  /** Local (IST) departure window, "HH:MM". */
  @Column('time', { name: 'window_from', nullable: true, transformer: hhmm }) windowFrom!:
    string | null;
  @Column('time', { name: 'window_to', nullable: true, transformer: hhmm }) windowTo!:
    string | null;
  @Column('integer') pax!: number;
  @Column('text', { nullable: true }) category!: AircraftCategory | null;
  @Column('text') status!: LegStatus;
  @Column('text', { nullable: true }) notes!: string | null;
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt!: Date;
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' }) updatedAt!: Date;
}

@Audited('rate_request', { ignore: ['createdBy'] })
@Entity('rate_request')
export class RateRequest {
  @PrimaryGeneratedColumn('uuid') id!: string;
  @Column('uuid', { name: 'wedding_id' }) weddingId!: string;
  @Column('uuid', { name: 'operator_id' }) operatorId!: string;
  @Column('text') channel!: 'WHATSAPP' | 'EMAIL' | 'PHONE' | 'OTHER';
  @Column('timestamptz', { name: 'sent_at' }) sentAt!: Date;
  @Column('uuid', { name: 'document_id', nullable: true }) documentId!: string | null;
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt!: Date;
  @Column('uuid', { name: 'created_by', nullable: true }) createdBy!: string | null;
}

@Entity('rate_request_leg')
export class RateRequestLeg {
  @PrimaryColumn('uuid', { name: 'rate_request_id' }) rateRequestId!: string;
  @PrimaryColumn('uuid', { name: 'leg_id' }) legId!: string;
}

@Audited('rate_response', { ignore: ['createdBy', 'rawText'] })
@Entity('rate_response')
export class RateResponse {
  @PrimaryGeneratedColumn('uuid') id!: string;
  @Column('uuid', { name: 'wedding_id' }) weddingId!: string;
  @Column('uuid', { name: 'operator_id' }) operatorId!: string;
  @Column('uuid', { name: 'rate_request_id', nullable: true }) rateRequestId!: string | null;
  @Column('uuid', { name: 'aircraft_id', nullable: true }) aircraftId!: string | null;
  @Column('text', { name: 'aircraft_text', nullable: true }) aircraftText!: string | null;
  @Column('integer', { nullable: true }) seats!: number | null;
  /** Operator's net rate for everything this reply covers (paise, ex-GST). Never shown to partners or clients. */
  @Column('bigint', { name: 'net_rate', transformer: paise }) netRate!: number;
  @Column('text', { nullable: true }) inclusions!: string | null;
  @Column('text', { nullable: true }) exclusions!: string | null;
  @Column('text', { name: 'cancellation_terms', nullable: true }) cancellationTerms!: string | null;
  @Column('jsonb', { name: 'cancellation_schedule', nullable: true })
  cancellationSchedule!: CancellationSchedule | null;
  @Column('timestamptz', { name: 'valid_until', nullable: true }) validUntil!: Date | null;
  @Column('timestamptz', { name: 'received_at' }) receivedAt!: Date;
  @Column('text', { name: 'raw_text', nullable: true }) rawText!: string | null;
  @Column('text') source!: 'MANUAL' | 'AI';
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt!: Date;
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' }) updatedAt!: Date;
  @Column('uuid', { name: 'created_by', nullable: true }) createdBy!: string | null;
}

/** Which legs a reply covers and how its cost splits between them (a package rate covers several). */
@Entity('rate_response_leg')
export class RateResponseLeg {
  @PrimaryColumn('uuid', { name: 'rate_response_id' }) rateResponseId!: string;
  @PrimaryColumn('uuid', { name: 'leg_id' }) legId!: string;
  @Column('bigint', { name: 'cost_share', transformer: paise }) costShare!: number;
}

/** The reply (or replies, for several jets) chosen for a leg. */
@Entity('leg_choice')
export class LegChoice {
  @PrimaryColumn('uuid', { name: 'leg_id' }) legId!: string;
  @PrimaryColumn('uuid', { name: 'rate_response_id' }) rateResponseId!: string;
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt!: Date;
}

export const WEDDING_ENTITIES = [
  Wedding,
  Leg,
  RateRequest,
  RateRequestLeg,
  RateResponse,
  RateResponseLeg,
  LegChoice,
];
